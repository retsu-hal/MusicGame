#include "main.h"
#include "Manager.h"
#include "Input.h"
#include "Notelane.h"
#include "GameSession.h"

#include "GameScene.h"
#include "ResultScene.h"
#include "TitleScene.h"

//==============================================================================
//初期化処理
//==============================================================================
void GameScene::Init()
{
	m_Lane = Manager::AddGameObject<Notelane>();

	// 選曲画面などで決めた譜面を読み込んで、カウントイン付きで開始
	if (m_Lane->LoadChart(GameSession::chartPath))
		m_Lane->PlayFromStart();
}

//==============================================================================
//終了処理
//==============================================================================
void GameScene::Uninit()
{
}

//==============================================================================
//更新処理
//==============================================================================
void GameScene::Update()
{
	// 曲が終わったらリザルトへ（結果は Notelane が GameSession に書いてある）
	if (m_Lane && m_Lane->IsFinished())
		Manager::ChangeScene<ResultScene>();

	// Esc：途中でやめてタイトルへ
	if (Input::GetKeyTrigger(VK_ESCAPE))
		Manager::ChangeScene<TitleScene>();
}

//==============================================================================
//描画処理
//==============================================================================
void GameScene::Draw()
{
}
